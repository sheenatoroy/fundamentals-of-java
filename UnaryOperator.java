public class UnaryOperator {
    public static void main(String[] args) {
        
        //Java Unary Operators

        int a = 10; 
        int b = 5;
        int result1, result2;
        
        System.out.println("Value of a: " + a);

        result1 = ++a;
        System.out.println("Result of ++a: " + result1);
        
        System.out.println("Value of b: " + b);

        //decrement operator
        result2 = --b;
        System.out.println("Result of --b: " + result2);
    }
}
