public class LogicalOperators {
    public static void main(String[] args) {
        
        //Java Logical Operators

        int a = 10;
        int b = 5;

        System.out.println((a > b) && (a < 20)); //true
        System.out.println((a > b) || (a < 20)); //true
        System.out.println(!(a > b)); //false
    }
}
